export function toAscii(text) {
  const rows = ["", "", "", "", ""];
  for (const ch of text.toUpperCase().split("")) {
    const glyph = FONT[ch] || [ch + " ", ch + " ", ch + " ", ch + " ", ch + " "];
    glyph.forEach((line, i) => { rows[i] += line + " "; });
  }
  return rows.join("\n").replace(/[ \t]+$/gm, "");
}

